# --------------------------------------------------------------------------- haversine_m


def test_haversine_same_point_is_zero():
    assert haversine_m(50.45, 30.52, 50.45, 30.52) == pytest.approx(0.0, abs=1e-6)


def test_haversine_known_distance_kyiv_pair():
    # Maidan Nezalezhnosti monument -> the branch's own known-wrong Pexels cell, both real
    # coordinates already used in this wave's measured report (00-existing-state.md §2):
    # 50.4502431N,30.5240622E vs the "17/76646/44193" tile center, ~775m per the branch's own
    # finding -- loose bounds since our tile-center math differs slightly from the branch's.
    truth = (50.4502431, 30.5240622)
    wrong_cell_approx = (50.4572, 30.5195)  # north-west of truth, same ballpark as the real cell
    d = haversine_m(*truth, *wrong_cell_approx)
    assert 500.0 < d < 1200.0


def test_haversine_is_symmetric():
    a, b = (50.40, 30.60), (50.45, 30.65)
    assert haversine_m(*a, *b) == pytest.approx(haversine_m(*b, *a), rel=1e-9)


