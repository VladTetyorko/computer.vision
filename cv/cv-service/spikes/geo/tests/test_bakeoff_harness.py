def test_config_key_is_stable_and_distinguishes_every_axis():
    base = _config_key("pexels", "xfeat", True, 10)
    assert base == _config_key("pexels", "xfeat", True, 10)  # deterministic
    assert base != _config_key("pexels", "xfeat", False, 10)  # rectified axis
