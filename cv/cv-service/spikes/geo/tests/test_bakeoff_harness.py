def _outcome(true_lat, true_lon, top1_lat, top1_lon, similarity, distance_m):
    return metrics.QueryOutcome(
        query_id="q", true_lat=true_lat, true_lon=true_lon, timestamp_ms=None,
        top1_lat=top1_lat, top1_lon=top1_lon, top1_similarity=similarity, margin=0.1,
        top1_distance_m=distance_m, best5_within_100m=distance_m <= 100.0,
        encode_ms=10.0, search_ms=1.0, n_candidates=5,
    )


def test_compute_config_metrics_recall_and_false_fix_rate():
    outcomes = [
        _outcome(50.0, 30.0, 50.0, 30.0, 0.9, 5.0),  # good, high sim
        _outcome(50.0, 30.0, 51.0, 31.0, 0.85, 500.0),  # false fix if accepted at a low threshold
        _outcome(50.0, 30.0, 50.0001, 30.0001, 0.6, 15.0),  # good, lower sim
    ]
    config = metrics.compute_config_metrics(
        config_name="t", encoder_name="e", zoom=17, augmented=False, with_prior=False, outcomes=outcomes
    )
    assert config.n_queries == 3
    assert config.recall_at_1_100m == pytest.approx(2 / 3)
    assert 0.0 <= config.false_fix_rate <= 1.0


def test_report_render_smoke():
    outcomes = [_outcome(50.0, 30.0, 50.0, 30.0, 0.9, 5.0)]
    config = metrics.compute_config_metrics(
        config_name="smoke", encoder_name="eigenplaces_r18_512", zoom=17, augmented=False,
        with_prior=False, outcomes=outcomes,
    )
    verdict = report_mod.compute_encoder_verdict("eigenplaces_r18_512", [config])
    text = report_mod.render_markdown(
        run_id="test-run", smoke_test=True, configs=[config],
        encoder_verdicts=[verdict], verdict=verdict, notes=["a note"],
    )
    assert "smoke" in text
    assert isinstance(text, str) and len(text) > 0
