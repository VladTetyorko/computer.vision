# --------------------------------------------------------------------------- rerank pure math


def test_reprojection_rms_zero_for_a_perfect_identity_fit():
    from spikes.geo.rerank import _reprojection_rms

    pts = np.array([[0.0, 0.0], [10.0, 0.0], [10.0, 10.0], [0.0, 10.0], [5.0, 5.0]])
    H = np.eye(3)
    mask = np.ones((pts.shape[0], 1), dtype=np.uint8)
    rms = _reprojection_rms(pts, pts, H, mask)
    assert rms == pytest.approx(0.0, abs=1e-9)


def test_reprojection_rms_ignores_outlier_mask_entries():
    from spikes.geo.rerank import _reprojection_rms

    kp_query = np.array([[0.0, 0.0], [10.0, 0.0], [999.0, 999.0]])  # last is a wild outlier
    kp_tile = np.array([[0.0, 0.0], [10.0, 0.0], [-500.0, 500.0]])
    H = np.eye(3)
    mask = np.array([[1], [1], [0]], dtype=np.uint8)  # outlier excluded
    rms = _reprojection_rms(kp_query, kp_tile, H, mask)
    assert rms == pytest.approx(0.0, abs=1e-9)


def test_reprojection_rms_none_when_no_inliers():
    from spikes.geo.rerank import _reprojection_rms

    pts = np.array([[0.0, 0.0], [10.0, 0.0]])
    H = np.eye(3)
    mask = np.zeros((2, 1), dtype=np.uint8)
    assert _reprojection_rms(pts, pts, H, mask) is None


# --------------------------------------------------------------------------- manifest roundtrip


def test_manifest_roundtrip_preserves_altitude_meters(tmp_path: Path):
    frames = [
        QueryFrame(query_id="a", image_path=tmp_path / "a.jpg", lat=50.1, lon=30.1, heading=90.0, timestamp_ms=0, altitude_meters=75.5),
        QueryFrame(query_id="b", image_path=tmp_path / "b.jpg", lat=50.2, lon=30.2),  # no telemetry at all -- the Pexels shape
    ]
    manifest_path = tmp_path / "manifest.jsonl"
    write_manifest(manifest_path, frames)
    loaded = load_manifest(manifest_path)
    assert len(loaded) == 2
    assert loaded[0].altitude_meters == pytest.approx(75.5)
    assert loaded[0].heading == pytest.approx(90.0)
    assert loaded[1].altitude_meters is None
    assert loaded[1].heading is None


def test_pexels_fixture_manifest_is_a_single_grounded_location():
    # The committed fixture (H0's own harvest): 12 frames of a documented near-static hover, one
    # ground-truth point (VISUAL-GEO-V2-PLAN.md / 00-existing-state.md §2), no telemetry.
    manifest_path = Path(__file__).resolve().parents[1] / "fixtures" / "maidan-video-frames" / "manifest.jsonl"
    frames = load_manifest(manifest_path)
    assert len(frames) == 12
    lats = {f.lat for f in frames}
    lons = {f.lon for f in frames}
    assert lats == {50.4502431}
    assert lons == {30.5240622}
    assert all(f.heading is None and f.altitude_meters is None for f in frames)


